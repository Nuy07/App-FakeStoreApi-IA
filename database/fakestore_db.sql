-- =====================================================================
-- VISTA DE APOYO: catálogo listo para el endpoint GET /products.
-- security_invoker hace que la vista respete los permisos de quien la
-- consulta (ver la sección de seguridad al final).
-- =====================================================================
CREATE VIEW public.vista_catalogo_productos
WITH (security_invoker = true) AS
SELECT
    p.id,
    p.titulo,
    p.descripcion,
    p.precio,
    c.nombre AS categoria,
    p.imagen_url,
    p.stock,
    p.calificacion_promedio,
    p.calificacion_cantidad
FROM public.productos p
JOIN public.categorias c ON c.id = p.categoria_id
WHERE p.activo;

-- =====================================================================
-- TRIGGER: suma cada reseña nueva a la calificación del producto. Es
-- incremental para conservar las calificaciones que ya traen los datos de
-- prueba (que no tienen filas en resenas). El promedio se calcula con la
-- suma exacta, no con el promedio ya redondeado, para que no se congele.
-- En PostgreSQL todas las expresiones del SET usan los valores anteriores
-- de la fila, por eso el promedio suma NEW.calificacion y 1 explícitamente.
-- =====================================================================
CREATE FUNCTION public.sumar_resena()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
    UPDATE public.productos
    SET calificacion_suma = calificacion_suma + NEW.calificacion,
        calificacion_cantidad = calificacion_cantidad + 1,
        calificacion_promedio = ROUND((calificacion_suma + NEW.calificacion) / (calificacion_cantidad + 1), 1)
    WHERE id = NEW.producto_id;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_resenas_after_insert
AFTER INSERT ON public.resenas
FOR EACH ROW EXECUTE FUNCTION public.sumar_resena();

-- TRIGGER: mantiene al día carritos.fecha_actualizacion en cada cambio.
CREATE FUNCTION public.actualizar_fecha_carrito()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
    NEW.fecha_actualizacion := now() AT TIME ZONE 'utc';
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_carritos_before_update
BEFORE UPDATE ON public.carritos
FOR EACH ROW EXECUTE FUNCTION public.actualizar_fecha_carrito();

