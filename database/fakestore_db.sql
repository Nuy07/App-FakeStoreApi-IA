-- =====================================================================
-- 1. usuarios
--    Cuentas de la app (clientes, auditores y administradores). El
--    backend Python expone /auth/login y /auth/me contra esta tabla.
-- =====================================================================
CREATE TABLE public.usuarios (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR(50)     NOT NULL,   -- con el que se inicia sesión en la app
    nombre          VARCHAR(100)    NOT NULL,
    apellido        VARCHAR(100)    NOT NULL,
    email           VARCHAR(150)    NOT NULL,
    password_hash   VARCHAR(255)    NOT NULL,   -- hash bcrypt, nunca texto plano
    telefono        VARCHAR(20),
    rol             VARCHAR(10)     NOT NULL DEFAULT 'cliente'
                    CONSTRAINT chk_usuarios_rol CHECK (rol IN ('cliente', 'auditor', 'admin')),
    fecha_registro  TIMESTAMP       NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    activo          BOOLEAN         NOT NULL DEFAULT TRUE
);

-- Únicos sin distinguir mayúsculas: "Carlos_Exp" y "carlos_exp" son el mismo usuario.
CREATE UNIQUE INDEX uq_usuarios_username ON public.usuarios (lower(username));
CREATE UNIQUE INDEX uq_usuarios_email ON public.usuarios (lower(email));

-- =====================================================================
-- 2. direcciones
--    Direcciones de envío de cada usuario (relación 1:N).
-- =====================================================================
CREATE TABLE public.direcciones (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id          INTEGER         NOT NULL
                        REFERENCES public.usuarios (id) ON DELETE CASCADE ON UPDATE CASCADE,
    alias               VARCHAR(50)     DEFAULT 'Principal',   -- "Casa", "Oficina"
    calle               VARCHAR(150)    NOT NULL,
    numero_ext          VARCHAR(20),
    ciudad              VARCHAR(100)    NOT NULL,
    estado_provincia    VARCHAR(100),
    codigo_postal       VARCHAR(20)     NOT NULL,
    pais                VARCHAR(100)    NOT NULL DEFAULT 'México',
    latitud             NUMERIC(9,6),                          -- address.geolocation.lat
    longitud            NUMERIC(9,6),                          -- address.geolocation.long
    es_principal        BOOLEAN         NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_direcciones_usuario ON public.direcciones (usuario_id);

-- =====================================================================
-- 3. categorias
--    Catálogo de categorías de producto (equivalente a /products/categories).
--    El índice sobre lower(nombre) hace que "Café Frío" y "café frío"
--    sean la misma categoría, pero "electronica" y "electrónica" no.
-- =====================================================================
CREATE TABLE public.categorias (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(100)    NOT NULL,
    descripcion VARCHAR(255),
    imagen_url  VARCHAR(255)
);

CREATE UNIQUE INDEX uq_categorias_nombre ON public.categorias (lower(nombre));

-- =====================================================================
-- 4. productos
--    Catálogo de productos (equivalente a /products). DELETE /products
--    hace un borrado lógico (activo = FALSE) porque carritos y órdenes
--    conservan la referencia al producto.
-- =====================================================================
CREATE TABLE public.productos (
    id                      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo                  VARCHAR(200)    NOT NULL,
    descripcion             TEXT,
    precio                  NUMERIC(10,2)   NOT NULL
                            CONSTRAINT chk_productos_precio CHECK (precio >= 0),
    categoria_id            INTEGER         NOT NULL
                            REFERENCES public.categorias (id) ON DELETE RESTRICT ON UPDATE CASCADE,
    imagen_url              VARCHAR(2048),
    stock                   INTEGER         NOT NULL DEFAULT 0 CHECK (stock >= 0),
    calificacion_promedio   NUMERIC(2,1)    NOT NULL DEFAULT 0.0    -- rating.rate
                            CONSTRAINT chk_productos_calificacion CHECK (calificacion_promedio BETWEEN 0 AND 5),
    calificacion_cantidad   INTEGER         NOT NULL DEFAULT 0 CHECK (calificacion_cantidad >= 0),  -- rating.count
    calificacion_suma       NUMERIC(12,1)   NOT NULL DEFAULT 0.0,   -- suma de todas las calificaciones
    fecha_creacion          TIMESTAMP       NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    activo                  BOOLEAN         NOT NULL DEFAULT TRUE
);

CREATE INDEX idx_productos_categoria ON public.productos (categoria_id);
CREATE INDEX idx_productos_titulo ON public.productos (titulo);
-- Búsqueda de texto completo en español sobre título y descripción.
CREATE INDEX ft_productos_busqueda ON public.productos
    USING GIN (to_tsvector('spanish', titulo || ' ' || coalesce(descripcion, '')));

-- =====================================================================
-- 5. carritos
--    Un carrito por sesión de compra. Un usuario puede tener varios
--    carritos a lo largo del tiempo, pero la app sólo opera sobre el
--    que tenga estado='activo' (regla validada en el backend).
-- =====================================================================
CREATE TABLE public.carritos (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id          INTEGER         NOT NULL
                        REFERENCES public.usuarios (id) ON DELETE CASCADE ON UPDATE CASCADE,
    estado              VARCHAR(10)     NOT NULL DEFAULT 'activo'
                        CHECK (estado IN ('activo', 'convertido', 'abandonado')),
    fecha_creacion      TIMESTAMP       NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    fecha_actualizacion TIMESTAMP       NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);

CREATE INDEX idx_carritos_usuario ON public.carritos (usuario_id);
CREATE INDEX idx_carritos_estado ON public.carritos (estado);

-- =====================================================================
-- 6. carrito_items
--    Productos dentro de un carrito (relación N:M usuarios<->productos
--    resuelta a través de carritos).
-- =====================================================================
CREATE TABLE public.carrito_items (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carrito_id      INTEGER         NOT NULL
                    REFERENCES public.carritos (id) ON DELETE CASCADE ON UPDATE CASCADE,
    producto_id     INTEGER         NOT NULL
                    REFERENCES public.productos (id) ON DELETE RESTRICT ON UPDATE CASCADE,
    cantidad        INTEGER         NOT NULL DEFAULT 1
                    CONSTRAINT chk_carritoitems_cantidad CHECK (cantidad > 0),
    precio_unitario NUMERIC(10,2)   NOT NULL,     -- snapshot del precio al agregarlo
    fecha_agregado  TIMESTAMP       NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    CONSTRAINT uq_carrito_producto UNIQUE (carrito_id, producto_id)
);

CREATE INDEX idx_carritoitems_producto ON public.carrito_items (producto_id);

-- =====================================================================
-- 7. ordenes
--    Resultado del checkout de un carrito (compra confirmada).
-- =====================================================================
CREATE TABLE public.ordenes (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id      INTEGER         NOT NULL
                    REFERENCES public.usuarios (id) ON DELETE RESTRICT ON UPDATE CASCADE,
    direccion_id    INTEGER         NOT NULL
                    REFERENCES public.direcciones (id) ON DELETE RESTRICT ON UPDATE CASCADE,
    fecha_orden     TIMESTAMP       NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    estado          VARCHAR(10)     NOT NULL DEFAULT 'pendiente'
                    CHECK (estado IN ('pendiente', 'pagado', 'enviado', 'entregado', 'cancelado')),
    subtotal        NUMERIC(10,2)   NOT NULL,
    impuestos       NUMERIC(10,2)   NOT NULL DEFAULT 0,
    costo_envio     NUMERIC(10,2)   NOT NULL DEFAULT 0,
    total           NUMERIC(10,2)   NOT NULL
                    CONSTRAINT chk_ordenes_total CHECK (total >= 0),
    metodo_pago     VARCHAR(10)     NOT NULL DEFAULT 'tarjeta'
                    CHECK (metodo_pago IN ('tarjeta', 'paypal', 'efectivo'))
);

CREATE INDEX idx_ordenes_usuario ON public.ordenes (usuario_id);
CREATE INDEX idx_ordenes_direccion ON public.ordenes (direccion_id);
CREATE INDEX idx_ordenes_estado ON public.ordenes (estado);

-- =====================================================================
-- 8. orden_items
--    Detalle de productos por orden (histórico, independiente del
--    carrito que le dio origen).
-- =====================================================================
CREATE TABLE public.orden_items (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orden_id        INTEGER         NOT NULL
                    REFERENCES public.ordenes (id) ON DELETE CASCADE ON UPDATE CASCADE,
    producto_id     INTEGER         NOT NULL
                    REFERENCES public.productos (id) ON DELETE RESTRICT ON UPDATE CASCADE,
    cantidad        INTEGER         NOT NULL
                    CONSTRAINT chk_ordenitems_cantidad CHECK (cantidad > 0),
    precio_unitario NUMERIC(10,2)   NOT NULL,
    subtotal        NUMERIC(10,2)   NOT NULL
);

CREATE INDEX idx_ordenitems_orden ON public.orden_items (orden_id);
CREATE INDEX idx_ordenitems_producto ON public.orden_items (producto_id);

-- =====================================================================
-- 9. resenas
--    Reseñas/calificaciones de producto por usuario (1 reseña por
--    usuario y producto).
-- =====================================================================
CREATE TABLE public.resenas (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id     INTEGER         NOT NULL
                    REFERENCES public.productos (id) ON DELETE CASCADE ON UPDATE CASCADE,
    usuario_id      INTEGER         NOT NULL
                    REFERENCES public.usuarios (id) ON DELETE CASCADE ON UPDATE CASCADE,
    calificacion    SMALLINT        NOT NULL
                    CONSTRAINT chk_resenas_calificacion CHECK (calificacion BETWEEN 1 AND 5),
    comentario      TEXT,
    fecha           TIMESTAMP       NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    CONSTRAINT uq_resena_usuario_producto UNIQUE (producto_id, usuario_id)
);

CREATE INDEX idx_resenas_usuario ON public.resenas (usuario_id);

